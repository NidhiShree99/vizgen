import io
from fpdf import FPDF

_REPLACEMENTS = {
    "—": "-", "–": "-", "‘": "'", "’": "'",
    "“": '"', "”": '"', "…": "...", "•": "-",
}


def _safe_text(text):
    if not text:
        return ""
    for bad, good in _REPLACEMENTS.items():
        text = text.replace(bad, good)
    return text.encode("latin-1", errors="ignore").decode("latin-1")


def _write(pdf, height, text):
    # fpdf2's multi_cell leaves the cursor at the right margin
    # instead of resetting it, so every block needs an explicit
    # reset to the left margin first.
    pdf.set_x(pdf.l_margin)
    pdf.multi_cell(0, height, text)


def generate_dashboard_pdf(dashboard_name, tiles, insight=None):
    """
    Build a PDF with a title page, optional executive summary,
    and one page per chart tile (rendered via kaleido).
    Returns PDF bytes.
    """
    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)

    pdf.add_page()
    pdf.set_font("Helvetica", "B", 22)
    _write(pdf, 12, _safe_text(dashboard_name))
    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(120, 120, 120)
    _write(pdf, 8, "Generated by VizGen")
    pdf.set_text_color(0, 0, 0)

    if insight and insight.get("holistic_summary"):
        pdf.ln(6)
        pdf.set_font("Helvetica", "B", 14)
        _write(pdf, 9, "Executive Summary")
        pdf.set_font("Helvetica", "", 11)
        _write(pdf, 7, _safe_text(insight["holistic_summary"]))

        chart_insights = insight.get("chart_insights", [])
        if chart_insights:
            pdf.ln(3)
            pdf.set_font("Helvetica", "B", 12)
            _write(pdf, 8, "Per-Chart Insights")
            pdf.set_font("Helvetica", "", 10)
            for ci in chart_insights:
                pdf.set_font("Helvetica", "B", 10)
                _write(pdf, 6, _safe_text(ci.get("chart", "")))
                pdf.set_font("Helvetica", "", 10)
                _write(pdf, 6, _safe_text(ci.get("insight", "")))
                pdf.ln(1)

    for tile in tiles:
        config = tile["config"]
        fig = tile["fig"]

        pdf.add_page()
        pdf.set_font("Helvetica", "B", 14)
        _write(pdf, 10, _safe_text(config.get("title", "")))

        png_bytes = fig.to_image(
            format="png", width=1000, height=550, scale=2)
        img_buffer = io.BytesIO(png_bytes)
        pdf.image(img_buffer, x=10, w=190)

    output = pdf.output()
    return bytes(output)
